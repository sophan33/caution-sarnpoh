CREATE DATABASE IF NOT EXISTS caution_db
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE caution_db;

CREATE TABLE IF NOT EXISTS articles (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  title_km   VARCHAR(255) NOT NULL,
  title_en   VARCHAR(255) DEFAULT NULL,
  body_km    TEXT NOT NULL,
  body_en    TEXT DEFAULT NULL,
  published  TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE USER IF NOT EXISTS 'caution_user'@'localhost' IDENTIFIED BY 'CHANGE_ME_NOW';
GRANT SELECT, INSERT, UPDATE, DELETE ON caution_db.* TO 'caution_user'@'localhost';
FLUSH PRIVILEGES;
